"""Hangar grime decals: 9 procedural 1024 px textures (colour png + translucency mask png) and csgo_static_overlay vmats
into out/addon/materials/ifr/grime (deploy.sh copies them to the content addon). Deterministic (seeded).
usage: python -I tools/grime.py [--no-compile]   (also copies to the real content addon and compiles the vmats there)
"""
import os, sys, shutil, subprocess
import numpy as np
from PIL import Image, ImageFilter
HERE = os.path.dirname(os.path.abspath(__file__)); PROJ = os.path.normpath(os.path.join(HERE, '..'))
REL = 'materials/ifr/grime'
OUT = os.path.join(PROJ, 'out', 'addon', REL)
CONTENT = r'C:\Program Files (x86)\Steam\steamapps\common\Counter-Strike Global Offensive\content\csgo_addons\mg_ironframe_dunes'
RC = r'C:\Program Files (x86)\Steam\steamapps\common\Counter-Strike Global Offensive\game\bin\win64\resourcecompiler.exe'
N = 1024
BRIGHT = 0.6

VMAT = """// %(name)s: IRONFRAME hangar grime decal (procedural, generated by tools/grime.py)
Layer0
{
	shader "csgo_static_overlay.vfx"
	F_BLEND_MODE 1
	g_flModelTintAmount "1.000"
	g_fTextureColorBrightness "%(b).3f"
	g_fTextureColorContrast "1.000"
	g_fTextureColorSaturation "1.000"
	g_vColorTint "[1.000000 1.000000 1.000000 0.000000]"
	TextureColor "%(rel)s/%(name)s.png"
	g_bFogEnabled "1"
	g_nTextureAddressModeU "1"
	g_nTextureAddressModeV "1"
	g_flOpacityScale "1.000"
	TextureTranslucency "%(rel)s/%(name)s_mask.png"
}
"""


def fbm(seed, oct=6, base=4, size=N, gain=0.5, aniso=(1, 1)):
    r = np.random.RandomState(seed); out = np.zeros((size, size), np.float32); amp = 1.0; tot = 0
    for o in range(oct):
        gx, gy = max(2, int(base * aniso[0] * 2 ** o)), max(2, int(base * aniso[1] * 2 ** o))
        g = Image.fromarray(r.rand(gy, gx).astype(np.float32), 'F').resize((size, size), Image.BICUBIC)
        out += amp * np.asarray(g); tot += amp; amp *= gain
    out /= tot; return (out - out.min()) / (out.max() - out.min() + 1e-6)

def sstep(a, b, x): t = np.clip((x - a) / (b - a + 1e-9), 0, 1); return t * t * (3 - 2 * t)
YY, XX = np.mgrid[0:N, 0:N].astype(np.float32) / N

def save(name, rgb, alpha):
    os.makedirs(OUT, exist_ok=True)
    a = np.clip(alpha, 0, 1)
    Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8), 'RGB').save(os.path.join(OUT, name + '.png'))
    Image.fromarray((a * 255).astype(np.uint8), 'L').save(os.path.join(OUT, name + '_mask.png'))
    open(os.path.join(OUT, name + '.vmat'), 'w', newline='\n').write(VMAT % dict(name=name, rel=REL, b=BRIGHT))

def colour(base, var, n):
    return np.stack([base[i] + (n - 0.5) * var for i in range(3)], -1)

def blob(seed, cx=.5, cy=.5, r=.32, warp=.35, fall=.16):
    d = np.hypot(XX - cx, YY - cy) / r
    w = (fbm(seed, 6, 3) - .5) * warp * 2 + (fbm(seed + 1, 5, 9) - .5) * .25
    return 1 - sstep(1 - fall * 2, 1 + fall, d + w)

def oil_stain(seed):
    m = blob(seed, r=.30, warp=.5)
    core = sstep(.3, .9, m)
    sheen = fbm(seed + 5, 5, 6)
    spots = np.zeros((N, N), np.float32); r = np.random.RandomState(seed)
    for _ in range(26):                           # satellite drops
        a = r.rand() * 6.28; dist = .30 + r.rand() * .16; x, y = .5 + np.cos(a) * dist, .5 + np.sin(a) * dist; rad = .006 + r.rand() * .02
        spots = np.maximum(spots, 1 - sstep(rad * .6, rad, np.hypot(XX - x, YY - y)))
    a = np.maximum(m * (.55 + .4 * core), spots * .8) * (.8 + .2 * fbm(seed + 9, 6, 14))
    rgb = colour((24, 20, 16), 26, sheen) + (sheen[..., None] > .72) * np.array([6, 10, 18])   # faint bluish sheen
    return rgb, a * .92

def tyre_skid(seed):
    r = np.random.RandomState(seed)
    t = np.linspace(0, 1, 4000); bend = .22 + r.rand() * .2
    px = .06 + .88 * t; py = .5 + bend * np.sin(t * np.pi * (.8 + r.rand() * .5)) * (1 - .3 * t)
    a = np.zeros((N, N), np.float32)
    nz = fbm(seed + 3, 6, 5, aniso=(3, 1)); tread = fbm(seed + 4, 3, 40, aniso=(2, 1))
    dx = np.gradient(px); dy = np.gradient(py); ln = np.hypot(dx, dy)
    for off in (-.045, .045):
        qx = px - dy / ln * off; qy = py + dx / ln * off
        xi = np.clip((qx * N).astype(int), 0, N - 1); yi = np.clip((qy * N).astype(int), 0, N - 1)
        line = np.zeros((N, N), np.float32); line[yi, xi] = 1
        im = Image.fromarray((line * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.GaussianBlur(3))
        a = np.maximum(a, np.asarray(im, np.float32) / 255)
    fade = sstep(0, .12, XX) * (1 - sstep(.8, .97, XX))
    a = a * fade * sstep(.35, .7, nz * .8 + tread * .4 + .1) * 1.4
    rgb = colour((20, 19, 18), 16, fbm(seed + 8, 4, 10))
    return rgb, a * .8

def scorch(seed):
    d = np.hypot(XX - .5, YY - .5) / .5
    ang = np.arctan2(YY - .5, XX - .5)
    ray2 = (np.sin(ang * 11 + fbm(seed, 4, 5) * 9) * .5 + .5)
    w = (fbm(seed, 6, 4) - .5) * .55
    m = 1 - sstep(.25, .95, d + w * (.4 + d) - .12 * ray2 * d)
    inner = 1 - sstep(0, .5, d + w * .3)
    a = (m * (.35 + .5 * inner)) * (.65 + .35 * fbm(seed + 6, 6, 12))
    rgb = colour((16, 14, 12), 18, fbm(seed + 7, 5, 9)) + inner[..., None] * np.array([12, 0, -12])   # brownish burn centre
    return rgb, a * .95

def hazard_worn(seed):
    # a worn 45 degree yellow/black band across the middle quarter of the sheet
    band_h = .27
    ys = YY - .5
    mask = (np.abs(ys) < band_h / 2)
    s = (((XX + YY) / .09) % 1.0) < .5
    wear = fbm(seed, 7, 6); wear2 = fbm(seed + 3, 5, 24)
    scr = fbm(seed + 9, 5, 60, aniso=(1, .08))                       # long scratches
    paint = (1 - sstep(.45, .8, wear * .7 + wear2 * .35)) * (1 - .6 * sstep(.62, .8, scr))
    edge = sstep(0, .02, band_h / 2 - np.abs(ys) + (wear2 - .5) * .02)
    ends = sstep(0, .08, XX + (wear - .5) * .1) * sstep(0, .08, 1 - XX + (wear - .5) * .1)
    rgb = np.where(s[..., None], np.array([206, 160, 22]), np.array([28, 27, 26])).astype(np.float32)
    rgb = rgb * (.75 + .25 * wear2[..., None]) + (wear[..., None] - .5) * 18
    return rgb, mask * paint * edge * ends * .96

def water_streak(seed):
    cols = fbm(seed, 4, 40, aniso=(1, .02))[:1, :].repeat(N, 0)       # per-column intensity (1D noise)
    thin = fbm(seed + 1, 6, 30, aniso=(1, .1))
    streak = sstep(.45, .75, cols) * (.5 + .5 * thin)
    top = 1 - sstep(.0, .95, YY + (fbm(seed + 2, 5, 6) - .5) * .4)    # strongest at the top, fading down
    run = sstep(.0, .06, YY) * top
    a = streak * run * (.45 + .45 * fbm(seed + 3, 5, 7))
    pale = (fbm(seed + 4, 4, 14, aniso=(1, .15)) > .66) * (cols > .5)  # mineral crust at some edges
    rgb = colour((30, 32, 31), 14, fbm(seed + 5, 4, 9)); rgb = np.where(pale[..., None], np.array([150, 148, 138]), rgb)
    return rgb, np.where(pale, np.maximum(a, .22 * run), a)

def rust_bleed(seed):
    cols = fbm(seed, 4, 25, aniso=(1, .02))[:1, :].repeat(N, 0)
    spread = .08 + .30 * YY                                           # widens as it runs down
    cx = .5 + (fbm(seed + 2, 3, 3) - .5) * .15
    wide = np.exp(-((XX - cx) / spread) ** 2 * 1.4)
    thin = fbm(seed + 1, 6, 28, aniso=(1, .08))
    a = wide * sstep(.3, .8, cols * .6 + thin * .6) * (1 - sstep(.1, .98, YY + (fbm(seed + 3, 5, 5) - .5) * .35)) * sstep(0, .05, YY)
    a = np.maximum(a, np.exp(-((XX - cx) ** 2 + (YY - .04) ** 2) / .0012) * .9)   # the weeping bolt/seam
    rgb = colour((112, 54, 22), 40, fbm(seed + 6, 5, 11)) * (1 - .35 * YY[..., None])
    return rgb, a * .85

def oil_spatter(seed):
    r = np.random.RandomState(seed); a = np.zeros((N, N), np.float32)
    for _ in range(160):
        ang = r.rand() * 6.28; dist = (r.rand() ** 1.6) * .46; x, y = .5 + np.cos(ang) * dist, .5 + np.sin(ang) * dist
        rad = (.003 + r.rand() ** 3 * .028) * (1.2 - dist)
        a = np.maximum(a, 1 - sstep(rad * .5, rad, np.hypot(XX - x, YY - y)))
    a *= (.7 + .3 * fbm(seed, 5, 10))
    return colour((22, 18, 14), 22, fbm(seed + 1, 4, 8)), a * .9

def sand_drift(seed):
    m = blob(seed, r=.38, warp=.9, fall=.3) * fbm(seed + 1, 7, 10)
    ripple = np.sin((XX * .85 + YY * .5) * 150 + fbm(seed + 2, 4, 6) * 14) * .5 + .5
    n = fbm(seed + 3, 6, 16)
    a = sstep(.12, .7, m * 1.9) * (.5 + .3 * ripple) * (.7 + .3 * n)
    return colour((176, 142, 96), 40, n) * (.9 + .1 * ripple[..., None]), a * .8

TEXTURES = {
    'ifr_grime_oil_a': lambda: oil_stain(11), 'ifr_grime_oil_b': lambda: oil_stain(47),
    'ifr_grime_skid': lambda: tyre_skid(5), 'ifr_grime_scorch': lambda: scorch(23),
    'ifr_grime_hazard': lambda: hazard_worn(8), 'ifr_grime_water': lambda: water_streak(31),
    'ifr_grime_rust': lambda: rust_bleed(17), 'ifr_grime_spatter': lambda: oil_spatter(3),
    'ifr_grime_sand': lambda: sand_drift(9),
}

def main():
    for k, f in TEXTURES.items():
        rgb, a = f(); save(k, rgb, a); print('%-18s alpha mean %.3f' % (k, a.mean()))
    if '--no-compile' in sys.argv: return 0
    dst = os.path.join(CONTENT, REL); os.makedirs(dst, exist_ok=True)
    for fn in os.listdir(OUT): shutil.copy(os.path.join(OUT, fn), dst)
    bad = 0
    for k in TEXTURES:
        r = subprocess.run([RC, '-f', '-i', os.path.join(dst, k + '.vmat')], capture_output=True, text=True)
        ok = ' 0 failed' in r.stdout; bad += not ok
        print('compile %-18s %s' % (k, 'OK' if ok else 'FAIL ' + r.stdout[-300:]))
    return 1 if bad else 0

if __name__ == '__main__':
    sys.exit(main())
