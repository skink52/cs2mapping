// Joins the game code into (1) the CS2 map script out/addon/maps/scripts/cs16.js and (2) a Node module for the tests.
// The converted maps (_gen/maps.json) and the HUD texts (_gen/hud.json, from the player's own 1.6 files) are baked in.
// usage: node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const join = (dir) => fs.readdirSync(path.join(root, dir)).filter((f) => f.endsWith('.js')).sort()
  .map((f) => `// ---- ${dir}/${f}\n` + read(path.join(dir, f))).join('\n');

const core = join('src/core');
fs.mkdirSync(path.join(root, 'build'), { recursive: true });
fs.writeFileSync(path.join(root, 'build/core_test.cjs'), core + '\nmodule.exports = { WEAPONS, AMMO, EQUIP, BUY_MENU, REWARD, HIT_MULT, BY_CLASS, CLASSES, TEAM_T, TEAM_CT, '
  + 'armorAbsorb, isArmored, bulletDamage16, blastDamage16, fallDamage16, knifeDamage16, teamRewards, LossBonus, planPurchase, BUY_ALIASES, '
  + 'mapCountFor, activeMaps, splitTeam, assignMaps, lateMap, MapRound, overallResult, endReasonFor, resultText };\n');

const mapsFile = path.join(root, 'out/addon/_gen/maps.json');
if (!fs.existsSync(mapsFile)) { console.log('no out/addon/_gen/maps.json yet (run tools/convert_map.py): test module only'); process.exit(0); }
const hudFile = path.join(root, 'out/addon/_gen/hud.json');
const hudJson = fs.existsSync(hudFile) ? fs.readFileSync(hudFile, 'utf8') : 'null';
// only these names are imported from CS2 (all used by earlier maps); the other enums are copied from point_script.d.ts
const head = `import { Instance, CSInputs, CSDamageFlags, CSDamageTypes } from "cs_script/point_script";
const CSGearSlot = { INVALID: -1, RIFLE: 0, PISTOL: 1, KNIFE: 2, GRENADES: 3, C4: 4, BOOSTS: 5 };
const CSWeaponType = { KNIFE: 0, PISTOL: 1, SUBMACHINEGUN: 2, RIFLE: 3, SHOTGUN: 4, SNIPER_RIFLE: 5, MACHINEGUN: 6, C4: 7, TASER: 8, GRENADE: 9, EQUIPMENT: 10, STACKABLEITEM: 11, UNKNOWN: 12 };
const CSWeaponAttackType = { INVALID: -1, PRIMARY: 0, SECONDARY: 1 };
// Counter-Strike 1.6 in CS2 (mg_cs16). Generated by tools/build.mjs from src/ - edit those files, not this one.
`;
const out = head + core + `\nconst MAPS_JSON = ${fs.readFileSync(mapsFile, 'utf8')};\nconst HUD_JSON = ${hudJson};\n` + join('src/cs2');
fs.mkdirSync(path.join(root, 'out/addon/maps/scripts'), { recursive: true });
fs.writeFileSync(path.join(root, 'out/addon/maps/scripts/cs16.js'), out);
console.log('cs16.js', (out.length / 1024).toFixed(0), 'KB' + (hudJson === 'null' ? ' (no HUD texts yet)' : ''));
