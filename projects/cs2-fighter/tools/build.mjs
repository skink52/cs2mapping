// Build script: stitches the shared core into the CS2 script, a Node test module and the
// browser preview. Usage: node tools/build.mjs
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const src = (f) => fs.readFileSync(path.join(root, "src", f), "utf8");
const coreFiles = ["core_1_base.js", "core_2_moves.js", "core_3_fighter.js", "core_4_game.js"];
const core = coreFiles.map(src).join("\n\n");
const exportsList = "PB_VERSION, SIM_HZ, DT, IN, CHARACTERS, MOVES, POSES, PART, PART_COUNT, MODEL_LEN, MODEL_BALL_R, Game, Fighter, CpuBrain, AI_LEVELS, MAX_JUGGLE, MODES, MODE_LABEL, P_LEN, P_HX, P_HY, P_TL, P_HD, P_ROT, P_SC, P_FLIP, P_AUTO, P_FA0, P_FA1, P_BA0, P_BA1, makeRng, clamp, lerp, smooth01, copyPose, newPose, lerpPose, sampleKeys, buildMoveSet, buildPoseSet, NORMAL_IDS, SKELETON_UNITS, BASE_DIMS, resolvePose, skeletonLocal, makeSkeleton, limbRadius, LIMB_RADIUS_K, BLOCK_HALF_K";

fs.mkdirSync(path.join(root, "dist"), { recursive: true });
// Node test module
fs.writeFileSync(path.join(root, "dist", "core_node.mjs"), core + `\nexport { ${exportsList} };\n`);

// CS2 script (only if the adapter exists yet)
if (fs.existsSync(path.join(root, "src", "cs2_adapter.js"))) {
  const header = src("cs2_header.js");
  const adapter = src("cs2_adapter.js");
  const clipsPath = path.join(root, "dist", "rig_clips.json");
  const clips = fs.existsSync(clipsPath) ? fs.readFileSync(clipsPath, "utf8") : "{}";
  const script = header + "\n" + core + "\n\n// rig animation clips (generated by tools/anim_export.mjs)\nconst RIG_CLIPS = " + clips + ";\n\n" + adapter;
  fs.mkdirSync(path.join(root, "dist", "addon", "scripts"), { recursive: true });
  fs.writeFileSync(path.join(root, "dist", "addon", "scripts", "puppet_brawl.js"), script);
}
// Browser preview: content-only page for the Artifact, plus a standalone file for the zip
if (fs.existsSync(path.join(root, "src", "preview.html"))) {
  const tpl = src("preview.html");
  const prev = src("preview.js");
  const html = tpl.replace("/*__CORE__*/", () => core).replace("/*__PREVIEW__*/", () => prev);
  fs.mkdirSync(path.join(root, "dist", "artifact"), { recursive: true });
  fs.writeFileSync(path.join(root, "dist", "artifact", "puppet_brawl.html"), html);
  const standalone = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body>\n' + html + '\n</body>\n</html>\n';
  fs.writeFileSync(path.join(root, "dist", "puppet_brawl_preview.html"), standalone);
}
console.log("built", new Date().toISOString());
