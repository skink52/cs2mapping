// build_script.mjs: joins src/NN_*.js (name order) into out/addon/maps/scripts/mg_monsoon.js under ONE import line and bakes in
//   const LAYOUT  = <out/layout.json>   (tools/layout.py export; required)
//   const HUDDATA = <out/hud.json>      (tools/mv_hud.py; {} when it does not exist yet)
// usage: node tools/build_script.mjs [outfile]
// cs_script cannot read entity keyvalues, so when out/entities.json exists the mv_mountinfo_N "message" values
// ("<kind>:<team>") are copied into LAYOUT.mountinfo (unless layout.json already has one). See docs/SCRIPT.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IMPORTS = ['Instance', 'Entities', 'Console', 'GameRules', 'CSInputs', 'CSMoveType', 'CSDamageTypes', 'CSDamageFlags',
  'CSRoundEndReason', 'CustomCameraMode'];

export function build(outFile) {
  const srcDir = path.join(root, 'src');
  const files = fs.readdirSync(srcDir).filter((f) => /^\d\d_.*\.js$/.test(f)).sort();
  if (!files.length) throw new Error('build_script: no src/NN_*.js files');
  const readJson = (p, dflt) => {
    if (!fs.existsSync(p)) { if (dflt === undefined) throw new Error('build_script: missing ' + p); return dflt; }
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  };
  const layout = readJson(path.join(root, 'out/layout.json'));
  const hud = readJson(path.join(root, 'out/hud.json'), {});
  const entsPath = path.join(root, 'out/entities.json');
  if (!layout.mountinfo && fs.existsSync(entsPath)) {
    const info = {};
    for (const e of JSON.parse(fs.readFileSync(entsPath, 'utf8'))) {
      const m = /^mv_mountinfo_(\d+)$/.exec(e.name || '');
      if (m && typeof e.message === 'string') info[m[1]] = e.message;
    }
    if (Object.keys(info).length) layout.mountinfo = info;
  }
  let body = '';
  for (const f of files) {
    const text = fs.readFileSync(path.join(srcDir, f), 'utf8');
    if (/^\s*import\s/m.test(text)) throw new Error('build_script: ' + f + ' has its own import line');
    body += `// ---- ${f}\n` + text.replace(/\s+$/, '') + '\n\n';
  }
  const out = `// mg_monsoon.js - generated by tools/build_script.mjs from src/*.js. Do not edit; edit the sources.\n` +
    `// AI-generated (Claude) for skink52's mg_monsoon addon.\n` +
    `import { ${IMPORTS.join(', ')} } from "cs_script/point_script";\n\n` +
    `const LAYOUT = ${JSON.stringify(layout)};\n` +
    `const HUDDATA = ${JSON.stringify(hud)};\n\n` + body;
  const dest = outFile || path.join(root, 'out/addon/maps/scripts/mg_monsoon.js');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, out);
  return { dest, files, lines: out.split('\n').length, bytes: out.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = build(process.argv[2]);
  console.log(`build_script: ${r.files.length} files -> ${r.dest} (${r.lines} lines, ${r.bytes} bytes)`);
}
