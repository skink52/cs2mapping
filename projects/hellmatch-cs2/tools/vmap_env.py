"""Adds the environment to the user's current map: a moondome (sky shell) around every level with a toolsskybox shell
one unit inside it, and visibility hints (Lowest over the whole map, Low only in the lobby rooms).

usage: vmap_env.py <current.vmap> <out.vmap> <addon_out_dir>

Everything this writes is tagged with the vis group "fdm_env", so running it again replaces its own work and leaves
the rest of the map (including anything placed by hand in Hammer) untouched.
"""
import os, sys, json
sys.path.insert(0, os.path.dirname(__file__))
import dmx
from vmaplib import *
import vmaplib

SRC, OUTPATH, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
GROUP = 'fdm_env'
MOONDOME = 'materials/fdm/sky/moondome.vmat'
TOOLSSKY = 'materials/tools/toolsskybox.vmat'
ZS = 1.2
HINT_LOWEST, HINT_LOW = 9, 3

levels = json.load(open(os.path.join(OUT, '_gen/levels.json')))

d = dmx.DMX.load(SRC)
world = d.root.get('world')
vmaplib.init(d, OUT)

# ---------------------------------------------------------------- moondome material (same panorama as env_sky)
os.makedirs(os.path.join(OUT, 'materials/fdm/sky'), exist_ok=True)
open(os.path.join(OUT, 'materials/fdm/sky/moondome.vmat'), 'w', newline='\n').write('''// FreeDM moondome: mesh material that shows the sky (same panorama as env_sky), unlit, no shadows, no fog
Layer0
{
	shader "csgo_moondome.vfx"
	F_DO_NOT_CAST_SHADOWS 1
	g_vColorTint "[1.000000 1.000000 1.000000 0.000000]"
	TextureColor "materials/fdm/sky/moondome_color.png"
	g_flCubeParallax "0.000"
	g_bFogEnabled "0"
	TextureCubeMap "materials/fdm/sky/sky_color.png"
}
''')
Image.new('RGB', (16, 16), (255, 255, 255)).save(os.path.join(OUT, 'materials/fdm/sky/moondome_color.png'))

# ---------------------------------------------------------------- boxes
def level_box(L):
    ox, oy, oz = L['off']
    x0, y0, x1, y1 = L['bb']
    fl = min(s[0] for s in L['s']); ce = max(s[1] for s in L['s'])
    return (x0 + ox - 512, y0 + oy - 512, fl * ZS + oz - 256, x1 + ox + 512, y1 + oy + 512, ce * ZS + oz + 768)

boxes = [level_box(L) for L in levels]
LZ = -12000
lobby = [(-1536 / 2 - 64, -1536 / 2 - 64, LZ - 64, 1536 / 2 + 64, 1536 / 2 + 64, LZ + 384 + 64),
         (-400 - 64, 2600 - 400 - 64, LZ - 64, 400 + 64, 2600 + 400 + 64, LZ + 256 + 64),
         (-1024 - 64, 4200 - 512 - 64, LZ - 64, 1024 + 64, 4200 + 512 + 64, LZ + 256 + 64)]

# every box must stay clear of its neighbours (moondomes must not overlap)
for i, a in enumerate(boxes):
    for b in boxes[i + 1:]:
        assert a[3] <= b[0] or b[3] <= a[0] or a[4] <= b[1] or b[4] <= a[1] or a[5] <= b[2] or b[5] <= a[2], (a, b)

def shell(box, mat, inset):
    x0, y0, z0, x1, y1, z1 = box
    v, faces = box_faces(x0 + inset, y0 + inset, z0 + inset, x1 - inset, y1 - inset, z1 - inset)
    mesh_node(polymesh(v, faces, [mat] * 6, scale=1.0), GROUP)

def hint(box, kind):
    x0, y0, z0, x1, y1, z1 = box
    c = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2); h = ((x1 - x0) / 2, (y1 - y0) / 2, (z1 - z0) / 2)
    ent('visibility_hint', c, group=GROUP, hintType=str(kind),
        box_mins='%g %g %g' % (-h[0], -h[1], -h[2]), box_maxs='%g %g %g' % (h[0], h[1], h[2]))

for box in boxes:
    shell(box, MOONDOME, 0)
    shell(box, TOOLSSKY, 1)
    # no Low hint over the levels: nothing inside them blocks sight (the level props aren't occluders), and Low
    # hints over all 32 boxes made the visibility compile run for hours (~1.8 million regions, 18 million clusters)
for box in lobby:
    hint(box, HINT_LOW)
allb = boxes + lobby
whole = (min(b[0] for b in allb) - 256, min(b[1] for b in allb) - 256, min(b[2] for b in allb) - 256,
         max(b[3] for b in allb) + 256, max(b[4] for b in allb) + 256, max(b[5] for b in allb) + 256)
hint(whole, HINT_LOWEST)

# info_map_parameters: the script ends each CS2 round through its FireWinCondition input (T win / CT win / draw)
ent('info_map_parameters', (-32, 0, LZ + 64), group=GROUP, targetname='fdm_map_params', buying='3',
    usenormalspawnsfordm='1', disableautogenerateddmspawns='1')

# nav generation needs a walkable seed: a func_nav_markup volume just above the lobby floor (bots can't be added otherwise)
seed = ent('func_nav_markup', (0, 0, 0), group=GROUP, navProperty_NavGen='WALKABLESEED', flags='1')
v, faces = box_faces(-704, -704, LZ + 1, 704, 704, LZ + 40, inward=False)
seed.attr('children')[2].append(mesh_node(polymesh(v, faces, ['materials/tools/toolsnavattribute.vmat'] * 6, scale=1.0), GROUP, attach=False))

# music: one point_soundevent per track (the script starts and stops them)
mj = os.path.join(OUT, '_gen/music.json')
for k, t in enumerate(json.load(open(mj)) if os.path.exists(mj) else []):
    ent('point_soundevent', (-700 + k * 64, 400, LZ + 64), group=GROUP, targetname='fdm_mus_' + t['id'],
        soundName='fdm_music.' + t['id'], startOnSpawn='0', toLocalPlayer='0', stopOnNew='0', saveAndRestore='0')

# ---------------------------------------------------------------- sprite models and sounds added since the map was first made
# The first build put a prop_dynamic per sprite model in the cache room (so CS2 compiles and precaches them) and a
# point_soundevent per sound in the lobby; those live in the user's map now. Anything new (monster models and sounds)
# is added here, in the env group, so a rebuild replaces only its own additions.
def existing_names(classname, prefix):
    out = {}
    for c in world.attr('children')[2]:
        if c.type != 'CMapEntity': continue
        ep = c.get('entity_properties')
        if ep.get('classname') != classname: continue
        tn = ep.get('targetname') or ''
        if tn.startswith(prefix) and c.get('customVisGroup', '') != GROUP: out[tn] = c
    return out

sprites = json.load(open(os.path.join(OUT, '_gen/sprite_models.json')))
have_cache = existing_names('prop_dynamic', 'fdm_cache_')
taken = []
for c in have_cache.values():
    v = c.attr('origin')[2]
    taken.append((float(v[0]), float(v[1])))
missing_models = sorted(k for k in sprites if 'fdm_cache_' + k.lower() not in have_cache)
# a 32 x 40 grid over the cache room (0, 4200; 2048 x 1024), skipping spots the old props use (the props are not
# solid and never seen, they only make CS2 compile and precache the models)
grid = [(-1000 + i * 32, 3712 + j * 40) for j in range(25) for i in range(63)]
free = [g for g in grid if all(abs(g[0] - t[0]) > 24 or abs(g[1] - t[1]) > 24 for t in taken)]
assert len(free) >= len(missing_models), ('cache room full', len(free), len(missing_models))
for k, key in enumerate(missing_models):
    x, y = free[k]
    ent('prop_dynamic', (x, y, LZ + 8), group=GROUP, targetname='fdm_cache_%s' % key.lower(), model='models/fdm/spr/%s.vmdl' % key.lower(),
        solid='0', disableshadows='1')

SOUNDS = [l.split('"')[1][4:] for l in open(os.path.join(OUT, 'soundevents/soundevents_addon.vsndevts'))
          if l.strip().startswith('"fdm.') and 'base' not in l]
have_snd = existing_names('point_soundevent', 'fdm_snd_')
missing_snd = [sn for sn in SOUNDS if 'fdm_snd_' + sn not in have_snd]
for k, sn in enumerate(missing_snd):
    ent('point_soundevent', (-700 + (k % 20) * 64, 100 + (k // 20) * 64, LZ + 64), group=GROUP, targetname='fdm_snd_' + sn, soundName='fdm.' + sn,
        startOnSpawn='0', toLocalPlayer='0', stopOnNew='0', saveAndRestore='0')
print('env: %d new sprite models, %d new sounds added to the map' % (len(missing_models), len(missing_snd)))

# ---------------------------------------------------------------- level geometry props: always match the current build
def is_level_prop(c):
    if c.type != 'CMapEntity': return False
    ep = c.get('entity_properties')
    return ep.get('classname') in ('prop_static', 'prop_dynamic') and (ep.get('model') or '').startswith('models/fdm/m')

props = json.load(open(os.path.join(OUT, '_gen/props.json')))
for p in props:
    if p['mover'] or p.get('anim'):
        ent('prop_dynamic', p['origin'], targetname=p['name'], model=p['model'], solid='0', disableshadows='1', fademindist='-1')
    else:
        ent('prop_static', p['origin'], model=p['model'], solid='0', disableshadows='1', fademindist='-1', fademaxdist='0',
            rendertocubemaps='0', bakelighting='0', visoccluder='0')

# ---------------------------------------------------------------- replace our previous environment, keep everything else
kids = world.attr('children')
kept = [c for c in kids[2] if c.get('customVisGroup', '') != GROUP and not is_level_prop(c)]
removed = len(kids[2]) - len(kept)
kids[2] = kept + vmaplib.new_children

pre = {a[0]: a for a in d.prefix[0]}
refs = pre['map_asset_references'][2]
for m in (MOONDOME, TOOLSSKY, 'materials/tools/toolsnavattribute.vmat'):
    if m not in refs: refs.append(m)
names = pre['map_subasset_reference_names'][2]; cnts = pre['map_subasset_reference_counts'][2]
for cls in ('prop_static', 'prop_dynamic', 'point_soundevent'):
    k = sum(1 for c in kids[2] if c.type == 'CMapEntity' and c.get('entity_properties').get('classname') == cls)
    if cls in names: cnts[names.index(cls)] = k
for cls in ('visibility_hint', 'func_nav_markup', 'info_map_parameters'):
    k = vmaplib.counts[cls]
    if cls in names: cnts[names.index(cls)] = k
    else:
        pre['map_subasset_reference_types'][2].append('entity'); names.append(cls); cnts.append(k)
n = vmaplib.counts['visibility_hint']

d.elements = [d.root]
d.save(OUTPATH)
print('env: %d moondomes, %d hints (%d low, 1 lowest), replaced %d old nodes, map %s..%s -> %s' % (
    len(boxes), n, n - 1, removed, tuple(int(x) for x in whole[:3]), tuple(int(x) for x in whole[3:]), OUTPATH))
