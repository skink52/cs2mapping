// build_script.mjs: joins a cs_script's modules (NN_*.js, name order) into the one file a point_script runs, under ONE import line
// from "cs_script/point_script". Neutral fork of projects/monsoon-cs2/tools/build_script.mjs; the project's own settings live in a
// small JSON file next to its sources.
//
// usage: node create/build_script.mjs <build.json> [--out <file>] [--check]
//   --out    write here instead of the config's "out"
//   --check  build in memory and compare with the file on disk: exit 1 when it is stale (a gate step; writes nothing)
// build.json (paths relative to the JSON file's folder):
//   { "name": "mg_example",               // used in the header line
//     "modules": "modules",               // folder of NN_*.js (two digits, underscore, name)
//     "out": "mg_example.js",             // the shipped script
//     "imports": "auto",                  // or a list; "auto" = every const / enum exported by create/test/point_script.d.ts
//                                         //   that the modules use as a word (Instance, Entities, Console, GameRules, CS* enums)
//     "header": ["AI-generated (Claude) for skink52's mg_example addon."],   // comment lines after the "generated" line
//     "bake": { "LAYOUT": { "path": "../out/layout.json", "required": true },  // const <NAME> = <JSON file> (optional section;
//               "HUDDATA": { "path": "../out/hud.json", "default": {} } } }    //   a missing file uses "default", or fails if required)
// Rules: a module must not have its own import line; module text is copied as is (no transpiling); the output starts with the
// "generated, do not edit" line so nobody edits the joined file by hand. Also importable: build(configPath, { out, write }).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const DTS = path.join(here, 'test', 'point_script.d.ts');

function exportedNames() {
  const dts = fs.readFileSync(DTS, 'utf8');
  const names = new Set();
  // runtime values only: the API objects and the enums (an exported class is a type here; importing one is not known to work)
  for (const m of dts.matchAll(/^\s*export\s+(?:declare\s+)?(?:const|enum)\s+([A-Za-z_]\w*)/gm)) names.add(m[1]);
  // deprecated exports are never imported automatically (api.py --strict would flag them anyway)
  for (const m of dts.matchAll(/@deprecated[^\n]*\n\s*export\s+(?:declare\s+)?(?:const|enum)\s+([A-Za-z_]\w*)/g)) names.delete(m[1]);
  return names;
}

export function build(configPath, opts = {}) {
  const cfgFile = path.resolve(configPath);
  const base = path.dirname(cfgFile);
  const cfg = JSON.parse(fs.readFileSync(cfgFile, 'utf8'));
  const modDir = path.resolve(base, cfg.modules || 'modules');
  const files = fs.readdirSync(modDir).filter((f) => /^\d\d_.*\.js$/.test(f)).sort();
  if (!files.length) throw new Error('build_script: no NN_*.js modules in ' + modDir);
  let body = '';
  for (const f of files) {
    const text = fs.readFileSync(path.join(modDir, f), 'utf8').replace(/\r\n/g, '\n');
    if (/^\s*import\s/m.test(text)) throw new Error('build_script: ' + f + ' has its own import line');
    if (/^\s*export\s/m.test(text)) throw new Error('build_script: ' + f + ' has an export (modules share one scope; nothing is exported)');
    body += `// ---- ${f}\n` + text.replace(/\s+$/, '') + '\n\n';
  }
  let bakes = '';
  for (const [name, b] of Object.entries(cfg.bake || {})) {
    const p = path.resolve(base, b.path);
    let val;
    if (fs.existsSync(p)) val = JSON.parse(fs.readFileSync(p, 'utf8'));
    else if (b.required) throw new Error('build_script: missing ' + p + ' (baked as ' + name + ')');
    else val = b.default === undefined ? {} : b.default;
    bakes += `const ${name} = ${JSON.stringify(val)};\n`;
  }
  let imports;
  const known = exportedNames();
  if (!cfg.imports || cfg.imports === 'auto') {
    const code = body.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    imports = [...known].filter((n) => new RegExp('\\b' + n + '\\b').test(code)).sort();
  } else {
    imports = cfg.imports;
    const bad = imports.filter((n) => !known.has(n));
    if (bad.length) throw new Error('build_script: not exported by point_script.d.ts (or deprecated): ' + bad.join(', '));
  }
  if (!imports.length) throw new Error('build_script: the modules use nothing from cs_script/point_script');
  const out = `// ${cfg.out ? path.basename(cfg.out) : cfg.name + '.js'} - generated by create/build_script.mjs from ${path.relative(base, modDir).replace(/\\/g, '/') || '.'}/NN_*.js. Do not edit; edit the modules.\n` +
    (cfg.header || []).map((l) => '// ' + l + '\n').join('') +
    `import { ${imports.join(', ')} } from "cs_script/point_script";\n\n` + (bakes ? bakes + '\n' : '') + body;
  const dest = path.resolve(opts.out || path.resolve(base, cfg.out || cfg.name + '.js'));
  const r = { dest, files, imports, lines: out.split('\n').length - 1, bytes: Buffer.byteLength(out), text: out };
  if (opts.check) { r.stale = !fs.existsSync(dest) || fs.readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') !== out; return r; }
  if (opts.write !== false) { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, out); }
  return r;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const a = process.argv.slice(2);
  if (!a[0] || /^(-h|--help)$/.test(a[0])) { console.log('usage: node create/build_script.mjs <build.json> [--out <file>] [--check]'); process.exit(2); }
  const oi = a.indexOf('--out');
  try {
    const r = build(a[0], { out: oi >= 0 ? a[oi + 1] : undefined, check: a.includes('--check') });
    if (a.includes('--check')) {
      console.log(r.stale ? `build_script: STALE ${r.dest} (rebuild: node create/build_script.mjs ${a[0]})` : `build_script: up to date ${r.dest}`);
      process.exit(r.stale ? 1 : 0);
    }
    console.log(`build_script: ${r.files.length} modules -> ${r.dest} (${r.lines} lines, ${r.bytes} bytes; imports ${r.imports.join(', ')})`);
  } catch (e) { console.error(String(e.message || e)); process.exit(1); }
}
