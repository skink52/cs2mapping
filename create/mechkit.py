"""Mechanics through cs_script: bundle create/mech/*.js modules with a JSON config into one map script, give it a themed HUD, place it.

  python mechkit.py build <config.json> <addon content> [--name mech]   -> maps/scripts/<name>.js + panorama HUD (layout + css)
  python mechkit.py test <config.json> [--seconds 60] [--players 6]      -> runs the bundle on create/test/mock_point_script.mjs (Node)
  python mechkit.py themes                                               -> the HUD theme names

Config keys (each optional; see the header of each create/mech/*.js module for its fields):
  abilities  [{kind, key, cooldown, strength, duration, team}]      double jump, dash, jetpack, blink, flight, low gravity, speed, shield,
                                                                     invisibility, wallhack, heal, jump pads
  minigames  [{kind: gallery | race | collect, name, ...}]          controls [{kind: drone | car | turret, prop, ...}]
  weapons    [{weapon, kind: pierce | explosive | burst | knockback}] hideseek {...}   story {start, steps}
  mode       {name, commands: [convar lines], every_round, give: [weapons]}   (gen_gameplay.mode_config builds it)
  hud        {theme: glass | paper | neon | military | retro | minimal, rows: [[label, variable], ...]} (default rows from the modules used)
Library: bundle(config) -> js text; hud_files(config, name) -> {path: text}; place(config, name, origin) adds the point_script, the
custom_hud_layout, relays and info_map_parameters to the map open in vmaplib (vmapgen.open_map); triggers(...) wires a trigger / button
to a script input (RunScriptInput on the point_script). test(config) -> (exit code, mock output).

Ported from cs2-map-mcp's mechanics.py (script bundling from fragments with a JSON config literal), ui.py (six HUD themes) and the
abilities / minigames / control / weapons / hideseek / story modules (Rmgs123, MIT). Fresh code; tested on skink52's mock engine.
"""
import argparse, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
MECH = os.path.join(HERE, 'mech')
MOCK = os.path.join(HERE, 'test', 'mock_point_script.mjs')
MODULES = [('abilities', 'abilities.js', 'abilitiesInstall'), ('minigames', 'minigames.js', 'minigamesInstall'),
           ('controls', 'controls.js', 'controlsInstall'), ('weapons', 'weapons.js', 'weaponsInstall'),
           ('hideseek', 'hideseek.js', 'hideseekInstall'), ('story', 'story.js', 'storyInstall'), ('mode', 'mode.js', 'modeInstall')]
THEMES = {
    'glass':    dict(bg='rgba(20, 28, 40, 0.55)', fg='#e8f0ff', accent='#7fd4ff', border='rgba(255,255,255,0.25)', font='Stratum2', radius='8px'),
    'paper':    dict(bg='rgba(242, 232, 210, 0.92)', fg='#3a2c1c', accent='#a0522d', border='#8b6b45', font='Stratum2', radius='2px'),
    'neon':     dict(bg='rgba(5, 0, 20, 0.75)', fg='#f4f4ff', accent='#ff2bd6', border='#22f0ff', font='Stratum2', radius='0px'),
    'military': dict(bg='rgba(30, 36, 24, 0.85)', fg='#d8dcc0', accent='#c8a040', border='#5a6440', font='Stratum2', radius='0px'),
    'retro':    dict(bg='rgba(0, 0, 0, 0.85)', fg='#7cff7c', accent='#ffd23c', border='#7cff7c', font='Stratum2Mono', radius='0px'),
    'minimal':  dict(bg='rgba(0, 0, 0, 0.35)', fg='#ffffff', accent='#ffffff', border='rgba(0,0,0,0)', font='Stratum2', radius='4px'),
}
PANEL = 'mech_hud'


def _read(name):
    with open(os.path.join(MECH, name), encoding='utf-8') as f: return f.read()


def used(config):
    return [m for m in MODULES if config.get(m[0])]


def default_rows(config):
    rows = [('', 'msg')]
    for i, ab in enumerate(config.get('abilities') or []):
        if ab.get('kind') not in ('jump_pad', 'low_gravity', 'speed'): rows.append((ab['kind'].replace('_', ' '), 'ab%d' % i))
    for g in config.get('minigames') or []:
        rows += [(g['name'] + ' score', g['name'] + '_score'), ('time', g['name'] + '_time'), ('best', g['name'] + '_best')]
    if config.get('controls'): rows += [('', 'ctl'), ('speed', 'ctl_speed'), ('heat', 'ctl_heat')]
    if config.get('hideseek'): rows += [('', 'hs_phase'), ('time', 'hs_time'), ('hiders', 'hs_left')]
    if config.get('story'): rows += [('time', 'story_time')]
    return rows


def bundle(config, name='mech'):
    cfg = dict(config)
    cfg.setdefault('hud', {})
    cfg['hud'] = dict(cfg['hud'], entity=cfg['hud'].get('entity', name + '_hud'), panel=PANEL)
    parts = ['// %s: generated by create/mechkit.py from create/mech/*.js (modules: %s). Edit the config, not this file.'
             % (name, ', '.join(m[0] for m in used(config)) or 'core only'),
             'import { Instance, CSInputs } from "cs_script/point_script";',
             'const CONFIG = %s;' % json.dumps(cfg, separators=(',', ':'), sort_keys=True), _read('core.js')]
    for key, fn, install in used(config): parts.append(_read(fn))
    parts.append('\n'.join('%s();' % install for key, fn, install in used(config)) + '\nmechStart();\n')
    return '\n'.join(parts)


def hud_files(config, name='mech'):
    """{'panorama/layout/custom_game/<name>.xml': text, 'panorama/styles/custom_game/<name>.css': text}"""
    hud = config.get('hud') or {}
    t = THEMES.get(hud.get('theme', 'glass'))
    if t is None: raise ValueError('theme must be one of %s' % ', '.join(THEMES))
    rows = [tuple(r) for r in hud.get('rows') or default_rows(config)]
    body = ['\t\t<Panel id="%s" class="MechBox" hittest="false">' % PANEL]
    for i, (label, var) in enumerate(rows):
        body.append('\t\t\t<Panel class="MechRow" hittest="false">')
        if label: body.append('\t\t\t\t<Label class="MechLabel" text="%s" hittest="false" />' % label.replace('"', "'"))
        body.append('\t\t\t\t<Label id="mech_v%d" class="MechValue" text="{s:%s}" hittest="false" />' % (i, var))
        body.append('\t\t\t</Panel>')
    body.append('\t\t</Panel>')
    xml = ('<root>\n\t<styles>\n\t\t<include src="file://{resources}/styles/custom_game/%s.css" />\n\t</styles>\n'
           '\t<Panel class="MechWrap" hittest="false">\n%s\n\t</Panel>\n</root>\n' % (name, '\n'.join(body)))
    css = '\n'.join([
        '.MechWrap { width: 100%; height: 100%; }',
        '.MechBox { horizontal-align: right; vertical-align: top; margin-top: 160px; margin-right: 24px; width: 300px; flow-children: down;'
        ' background-color: %s; border: 2px solid %s; border-radius: %s; padding: 10px; }' % (t['bg'], t['border'], t['radius']),
        '.MechRow { width: 100%%; flow-children: right; margin-bottom: 4px; }',
        '.MechLabel { width: 45%%; color: %s; font-family: %s; font-size: 18px; text-transform: uppercase; }' % (t['accent'], t['font']),
        '.MechValue { width: fill-parent-flow(1.0); color: %s; font-family: %s; font-size: 20px; font-weight: bold; }' % (t['fg'], t['font']),
    ]).replace('%%', '%') + '\n'
    return {'panorama/layout/custom_game/%s.xml' % name: xml, 'panorama/styles/custom_game/%s.css' % name: css}


def build(config, content, name='mech'):
    out = {'maps/scripts/%s.js' % name: bundle(config, name)}
    out.update(hud_files(config, name))
    for rel, text in out.items():
        p = os.path.join(content, *rel.split('/')); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w', encoding='utf-8', newline='\n') as f: f.write(text)
    return sorted(out)


def place(config, name='mech', origin=(0, 0, 0), group=''):
    """point_script + custom_hud_layout (+ win relays for hideseek / story wired to info_map_parameters) in the vmaplib map"""
    import primitives as P
    nodes = [P.entity('point_script', origin, group=group, strict=False, targetname=name, cs_script='maps/scripts/%s.vjs' % name),
             P.entity('custom_hud_layout', (origin[0] + 16, origin[1], origin[2]), group=group, strict=False, targetname=name + '_hud',
                      layout='panorama/layout/custom_game/%s.vxml' % name, start_enabled=1)]
    relays = []
    if config.get('hideseek'):
        hs = config['hideseek']
        relays += [(hs.get('hiders_win', 'hs_hiders_win'), hs.get('hiders', 2)), (hs.get('seekers_win', 'hs_seekers_win'), hs.get('seekers', 3))]
    if config.get('story'): relays += [('story_win', 2), ('story_lose', 3)]
    if relays:
        params = P.entity('info_map_parameters', (origin[0] + 32, origin[1], origin[2]), group=group, strict=False, targetname=name + '_params')
        nodes.append(params)
        for i, (rname, team) in enumerate(relays):
            r = P.entity('logic_relay', (origin[0] + 48 + 16 * i, origin[1], origin[2]), group=group, strict=False, targetname=rname)
            P.connect(r, 'OnTrigger', name + '_params', 'FireWinCondition', 8 if team == 2 else 9, check_output=False)   # T win / CT win
            nodes.append(r)
    return nodes


def trigger(shape, script_input, script='mech', output='OnStartTouch', cls='trigger_multiple', group='', **keys):
    """a brush trigger / button whose output runs RunScriptInput <script_input> on the point_script (the activator is passed along)"""
    import primitives as P
    keys.setdefault('spawnflags', 1)
    e = P.brush_entity(cls, shape, group=group, **keys) if _known(cls) else _brush_loose(cls, shape, group, keys)
    P.connect(e, output, script, 'RunScriptInput', script_input, check_output=False)
    return e


def _known(cls):
    import primitives as P
    try: return P._cat().is_entity(cls)
    except Exception: return False


def _brush_loose(cls, shape, group, keys):
    import primitives as P, vmaplib
    v = shape[0]
    centre = tuple((min(p[i] for p in v) + max(p[i] for p in v)) / 2.0 for i in range(3))
    e = P.entity(cls, centre, group=group, strict=False, defaults=False, **keys)
    e.attr('children')[2].append(vmaplib.mesh_node(vmaplib.polymesh(*shape), group=group, attach=False))
    return e


def test(config, seconds=60, players=6, entities=None, node='node', extra=()):
    """run the bundle on the mock engine; -> (exit code, output). entities: [{name, cls, origin}] the script looks up"""
    with tempfile.TemporaryDirectory(prefix='mechkit_') as d:
        js = os.path.join(d, 'mech.js')
        with open(js, 'w', encoding='utf-8') as f: f.write(bundle(config))
        argv = [node, MOCK, js]
        if entities is not None:
            ej = os.path.join(d, 'entities.json')
            with open(ej, 'w', encoding='utf-8') as f: json.dump(entities, f)
            argv.append(ej)
        argv += ['players=%d' % players, 'seconds=%d' % seconds] + list(extra)
        r = subprocess.run(argv, capture_output=True, text=True, timeout=600, creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
        return r.returncode, r.stdout + r.stderr


def main(argv=None):
    ap = argparse.ArgumentParser(description='cs_script mechanics bundler')
    ap.add_argument('cmd', choices=['build', 'test', 'themes']); ap.add_argument('config', nargs='?'); ap.add_argument('content', nargs='?')
    ap.add_argument('--name', default='mech'); ap.add_argument('--seconds', type=int, default=60); ap.add_argument('--players', type=int, default=6)
    a = ap.parse_args(argv)
    if a.cmd == 'themes': print(' '.join(THEMES)); return 0
    with open(a.config, encoding='utf-8') as f: cfg = json.load(f)
    if a.cmd == 'build': print('\n'.join(build(cfg, a.content, a.name))); return 0
    code, out = test(cfg, a.seconds, a.players)
    print(out[-3000:]); return code


if __name__ == '__main__':
    sys.exit(main())
