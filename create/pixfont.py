CELL = 8
_cache = {}
def glyph(ch):
    """bool array 8x8 (rows x cols) for a character; unknown characters draw as a small box"""
    ch = ch.upper()
    if ch not in _cache:
        rows = GLYPHS.get(ch, ["#######.", "#.....#.", "#.....#.", "#.....#.", "#.....#.", "#.....#.", "#######.", "........"])
        _cache[ch] = np.array([[c == '#' for c in r] for r in rows], bool)
    return _cache[ch]

def text_mask(text, gap=0):
    """bool array (8, 8*len) with the glyphs side by side"""
    cols = [glyph(c) for c in text]
    if not cols: return np.zeros((8, 1), bool)
    out = np.zeros((8, len(cols) * (CELL + gap)), bool)
    for i, g in enumerate(cols): out[:, i * (CELL + gap):i * (CELL + gap) + 8] = g
    return out

def render(text, scale=4, color=(255, 255, 255), outline=None, shadow=None, gap=0, bg=None):
    """RGBA image of the text, nearest-neighbour upscaled. outline: colour of a 1-px (pre-scale) outline around
    every glyph; shadow: colour of a 1-px drop shadow down-right. bg: fill colour behind (default transparent)."""
    m = text_mask(text, gap)
    h, w = m.shape
    pad = 1 if (outline or shadow) else 0
    canvas = np.zeros((h + 2 * pad, w + 2 * pad, 4), np.uint8)
    if bg: canvas[:] = tuple(bg) + (255,)
    def put(mask, col, dy, dx):
        ys, xs = np.where(mask)
        canvas[ys + pad + dy, xs + pad + dx] = tuple(col) + (255,)
    if shadow: put(m, shadow, 1, 1)
    if outline:
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                if dy or dx: put(m, outline, dy, dx)
    put(m, color, 0, 0)
    return np.repeat(np.repeat(canvas, scale, 0), scale, 1)

def width(text, scale=1, gap=0):
    return len(text) * (CELL + gap) * scale

# ---------------------------------------------------------------- voxel letters (3D signs)
def text_voxels(text, gap=1):
    """bool array (rows=8, cols) of the text, for extruding into a mesh: rows are top-to-bottom"""
    return text_mask(text, gap)

# ---------------------------------------------------------------- composition helpers (loading screen, logo)
def paste(canvas, img, x, y):
    """alpha-paste an RGBA uint8 image onto an RGB(A) numpy canvas at (x, y) (clipped)"""
    h, w = img.shape[:2]
    H, W = canvas.shape[:2]
    x0, y0 = max(0, x), max(0, y); x1, y1 = min(W, x + w), min(H, y + h)
    if x1 <= x0 or y1 <= y0: return
    sub = img[y0 - y:y1 - y, x0 - x:x1 - x]
    a = sub[..., 3:4].astype(np.float32) / 255
    canvas[y0:y1, x0:x1, :3] = (canvas[y0:y1, x0:x1, :3] * (1 - a) + sub[..., :3] * a).astype(canvas.dtype)

def draw(canvas, x, y, text, scale=4, color=(255, 255, 255), outline=(0, 0, 0), shadow=None, align='left'):
    img = render(text, scale, color, outline=outline, shadow=shadow)
    if align == 'center': x -= img.shape[1] // 2
    elif align == 'right': x -= img.shape[1]
    paste(canvas, img, int(x), int(y))
    return img.shape[1]

def logo(text, scale=8, grad=None, shadow=((2, (110, 30, 120)),), bold=True):
    """chunky arcade logo: bold letters with a vertical colour gradient, a black outline and a drop shadow"""
    m = text_mask(text, gap=2 if bold else 1)
    if bold: m = m | np.roll(m, 1, 1)
    h, w = m.shape
    pad = 4
    big = np.zeros((h + pad * 2, w + pad * 2), bool); big[pad:pad + h, pad:pad + w] = m
    outl = big.copy()
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1): outl |= np.roll(np.roll(big, dy, 0), dx, 1)
    img = np.zeros(big.shape + (4,), np.uint8)
    for d, col in shadow:
        sh = np.roll(np.roll(outl, d, 0), d, 1)
        img[sh, :3] = col; img[sh, 3] = 255
    img[outl, :3] = (0, 0, 0); img[outl, 3] = 255
    grad = grad or [(255, 255, 255), (255, 240, 150), (255, 190, 40), (255, 190, 40), (220, 120, 30), (255, 100, 30), (220, 60, 200), (110, 30, 120)]
    ys, xs = np.where(big)
    for y, x in zip(ys, xs):
        img[y, x, :3] = grad[min(len(grad) - 1, y - pad)]; img[y, x, 3] = 255
    return np.repeat(np.repeat(img, scale, 0), scale, 1)
