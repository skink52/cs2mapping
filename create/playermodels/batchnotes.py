"""Batch notes: BATCH<n>.md rebuilt from the catalog and the reports, keeping the hand-written review notes.

usage: python3 -I batchnotes.py <catalog.json> <batch> [out.md]      (default: BATCH<n>.md next to the catalog)

Everything above the line '<!-- review notes: kept by batchnotes.py -->' is generated (header, table, items looked at and not used);
everything below it is copied from the existing file, so write the review there. Re-run after re-converting a batch.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fetch

MARK = '<!-- review notes: kept by batchnotes.py -->'


def main():
    cat_path, batch = sys.argv[1], int(sys.argv[2])
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(cat_path)), 'BATCH%d.md' % batch)
    cat = json.load(open(cat_path)); p = fetch.paths(cat)
    rows, n, ok, warn = [], 0, 0, 0
    for it in cat['items']:
        if not it.get('chosen') or it.get('batch') != batch: continue
        rp = os.path.join(p['work'], 'reports', it['slug'] + '.json')
        r = json.load(open(rp)) if os.path.exists(rp) else {}
        n += 1
        comp = r.get('compile', {}); ok += bool(comp.get('ok')); warn += bool(r.get('warnings'))
        jo = r.get('joint_offsets') or {}
        limb = max([v for k, v in jo.items() if k.startswith(('arm_', 'leg_', 'hand_', 'ankle_'))] or [0])
        hb = r.get('head_hitbox_shift')
        ff = r.get('finger_fit') or {}
        notes = list(r.get('warnings', []))
        for m in r.get('materials', []):
            if m.get('standin'): notes.append('%s: generated %s stand-in' % (m['source'], m['standin']))
            if m.get('glass'): notes.append('%s: dark see-through glass (no texture in the item)' % m['source'])
            if m.get('flat'): notes.append('%s: FLAT GREY (texture missing)' % m['source'])
        rows.append('| `%s` | [%s](https://steamcommunity.com/sharedfiles/filedetails/?id=%s) by %s | `%s` | %s | %s | %.1f | %s | %s | %s | %s | %s |' % (
            it['slug'], it['title'].replace('|', '/'), it['id'], it['author'], it['mdl'], r.get('triangles', ''), r.get('scale', ''), limb,
            r.get('chest_shift', ''), '%+.1f z' % hb[2] if hb else '', '/'.join('%.1f' % v for v in ff.values() if v is not None),
            'OK' if comp.get('ok') else ('FAILED' if comp else '-'), '; '.join(notes) or 'ok'))
    skipped = ['| %s | %s | %s |' % (it['id'], it['title'].replace('|', '/'), it.get('skip_reason', ''))
               for it in cat['items'] if not it.get('chosen') and it.get('looked_at') == batch]
    head = ['# Batch %d: %d GMod player models' % (batch, n), '',
            'Generated by `batchnotes.py` from `catalog.json` and the conversion reports (`<work>/reports/<slug>.json`); review notes below the',
            'marker are hand-written. All models: [MODELS.md](MODELS.md). Method and rules: [docs/creation/gmod-playermodels.md](../../docs/creation/gmod-playermodels.md).',
            '', '%d models, %d compiled, %d with fit warnings.' % (n, ok, warn), '',
            'Columns: **limb** = worst arm/leg joint distance from CS2\'s (u); **torso** = how far the upper torso was moved back (u); **head hb** = how far the',
            'head hit box moved (z, u); **fingers** = finger fit L/R (u, < 1.8 fine).', '',
            '| slug | workshop item | model | tris | scale | limb | torso | head hb | fingers | compile | notes |',
            '|---|---|---|---|---|---|---|---|---|---|---|'] + rows
    if skipped: head += ['', '## Looked at, not used', '', '| id | item | why |', '|---|---|---|'] + skipped
    keep = ''
    if os.path.exists(out):
        old = open(out, encoding='utf-8').read()
        if MARK in old: keep = old.split(MARK, 1)[1].strip('\n')
    txt = '\n'.join(head) + '\n\n' + MARK + '\n' + (keep + '\n' if keep else '\n## Review\n\n')
    open(out, 'w', encoding='utf-8', newline='\n').write(txt)
    print('%s: %d models' % (out, n))


if __name__ == '__main__':
    main()
