"""Own props through headless Blender: a template or your own bpy script (or an .obj / .fbx / .glb / .blend import) -> FBX render mesh +
convex collision FBX -> ModelDoc .vmdl in the addon. Blender is only started when you run it; --no-blender writes the script and vmdl only;
--dry-run writes nothing at all and prints what would be written.

  python blenderkit.py <addon content> <name> --template crate|barrel|pallet|table|lamp|pipe|sandbags|fence [--size W,D,H] [--material materials/...vmat]
  python blenderkit.py <addon content> <name> --script my_shape.py      (a bpy script that builds objects; objects named *_col are collision)
  python blenderkit.py <addon content> <name> --import model.glb        (scaled so 1 unit = 1 inch; base at z = 0, front +X)
  common: [--blender PATH] [--no-blender] [--dry-run] [--prefix props] [--surface wood]

Blender: --blender, env BLENDER, or blender.exe under Steam\\steamapps\\common\\Blender or Program Files\\Blender Foundation\\Blender*
(exact folders only). It runs with --background --factory-startup, no window. Output: <content>/models/<prefix>/<name>/<name>.fbx,
<name>_col.fbx, <name>.vmdl (import_scale 1: the script exports in inches) and a bounds JSON. Compile with tools/rcompile.py asset.
Materials: a Blender material named like a .vmat path ("materials/dev/reflectivity_50.vmat") is remapped to it in the vmdl.
Units follow cs2-map-mcp's rule: models are authored in CS2 units, base at z = 0, front along +X.

From models.py + blender/ (driver, templates) of cs2-map-mcp by Rmgs123 (github.com/Rmgs123/cs2-map-mcp, MIT): headless Blender, the
template set, _col collision objects, material remaps. Fresh code; the procedural, Blender-free path is create/build_prop.py.
"""
import argparse, glob, json, os, subprocess, sys

TEMPLATES = {
    # name: (default size W, D, H, body)  body is bpy code using W, D, H and helper box(name, x0,y0,z0,x1,y1,z1) / cyl(name, r, h, x, y, z, n)
    'crate': ((32, 32, 32), "box('body', -W/2, -D/2, 0, W/2, D/2, H)\nbox('body_col', -W/2, -D/2, 0, W/2, D/2, H)"),
    'barrel': ((24, 24, 44), "cyl('body', W/2, H, 0, 0, 0, 20)\ncyl('body_col', W/2, H, 0, 0, 0, 10)"),
    'pallet': ((48, 40, 6), "for i in range(5): box('slat%d' % i, -W/2, -D/2 + i * (D - 4) / 4, H - 1.5, W/2, -D/2 + i * (D - 4) / 4 + 4, H)\n"
                            "for i in range(3): box('beam%d' % i, -W/2, -D/2 + i * (D - 4) / 2, 0, W/2, -D/2 + i * (D - 4) / 2 + 4, H - 1.5)\n"
                            "box('all_col', -W/2, -D/2, 0, W/2, D/2, H)"),
    'table': ((48, 30, 30), "box('top', -W/2, -D/2, H - 2, W/2, D/2, H)\n"
                            "for sx in (-1, 1):\n    for sy in (-1, 1): box('leg', sx * (W/2 - 3) - 1, sy * (D/2 - 3) - 1, 0, sx * (W/2 - 3) + 1, sy * (D/2 - 3) + 1, H - 2)\n"
                            "box('top_col', -W/2, -D/2, H - 2, W/2, D/2, H)"),
    'lamp': ((10, 10, 96), "cyl('pole', 1.5, H - 8, 0, 0, 0, 8)\ncyl('head', W/2, 8, 0, 0, H - 8, 12)\ncyl('pole_col', 2, H, 0, 0, 0, 6)"),
    'pipe': ((8, 8, 128), "cyl('pipe', W/2, H, 0, 0, 0, 12)\ncyl('pipe_col', W/2, H, 0, 0, 0, 8)"),
    'sandbags': ((48, 16, 24), "for r in range(3):\n    for i in range(2): box('bag', -W/2 + i * W/2 + (r % 2) * 4 - 2, -D/2, r * H/3, i * W/2 + (r % 2) * 4 - 2, D/2, (r + 1) * H/3)\n"
                               "box('all_col', -W/2, -D/2, 0, W/2, D/2, H)"),
    'fence': ((96, 4, 48), "for i in range(5): box('post', -W/2 + i * (W - 4) / 4, -D/2, 0, -W/2 + i * (W - 4) / 4 + 4, D/2, H)\n"
                           "for z in (H * 0.3, H * 0.8): box('rail', -W/2, -D/4, z - 2, W/2, D/4, z + 2)\nbox('all_col', -W/2, -D/2, 0, W/2, D/2, H)"),
}

HEADER = r'''# generated by create/blenderkit.py; run: blender --background --factory-startup --python <this file>
import bpy, json, math, os
OUT = {out!r}; NAME = {name!r}; MATERIAL = {material!r}
bpy.ops.wm.read_factory_settings(use_empty=True)
for u in (bpy.context.scene.unit_settings,): u.system = 'NONE'
def _mat(obj):
    m = bpy.data.materials.get(MATERIAL) or bpy.data.materials.new(MATERIAL)
    obj.data.materials.append(m)
def box(name, x0, y0, z0, x1, y1, z1):
    bpy.ops.mesh.primitive_cube_add(size=1)
    o = bpy.context.active_object; o.name = name
    o.scale = (abs(x1 - x0), abs(y1 - y0), abs(z1 - z0)); o.location = ((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
    bpy.ops.object.transform_apply(location=True, scale=True); _mat(o); return o
def cyl(name, r, h, x, y, z, n=16):
    bpy.ops.mesh.primitive_cylinder_add(vertices=n, radius=r, depth=h, location=(x, y, z + h / 2))
    o = bpy.context.active_object; o.name = name; bpy.ops.object.transform_apply(location=True); _mat(o); return o
'''

FOOTER = r'''
objs = [o for o in bpy.context.scene.objects if o.type == 'MESH']
if not objs: raise SystemExit('nothing was built')
lo = [min(min((o.matrix_world @ v.co)[i] for v in o.data.vertices) for o in objs) for i in range(3)]
hi = [max(max((o.matrix_world @ v.co)[i] for v in o.data.vertices) for o in objs) for i in range(3)]
if IMPORTED:
    s = TARGET / max(hi[2] - lo[2], 1e-6) if TARGET else 1.0
    for o in objs:
        o.location = (o.location[0] - (lo[0] + hi[0]) / 2, o.location[1] - (lo[1] + hi[1]) / 2, o.location[2] - lo[2])
        o.scale = (o.scale[0] * s, o.scale[1] * s, o.scale[2] * s)
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.transform_apply(location=True, scale=True)
    lo = [min(min((o.matrix_world @ v.co)[i] for v in o.data.vertices) for o in objs) for i in range(3)]
    hi = [max(max((o.matrix_world @ v.co)[i] for v in o.data.vertices) for o in objs) for i in range(3)]
cols = [o for o in objs if o.name.lower().endswith('_col') or '_col.' in o.name.lower()]
render = [o for o in objs if o not in cols]
if not cols:                                   # no collision given: the convex hull of everything
    bpy.ops.object.select_all(action='DESELECT')
    for o in render: o.select_set(True)
    bpy.context.view_layer.objects.active = render[0]
    bpy.ops.object.duplicate(); bpy.ops.object.join()
    hull = bpy.context.active_object; hull.name = 'auto_col'
    bpy.ops.object.mode_set(mode='EDIT'); bpy.ops.mesh.select_all(action='SELECT'); bpy.ops.mesh.convex_hull(); bpy.ops.object.mode_set(mode='OBJECT')
    cols = [hull]
def export(objs_, path):
    bpy.ops.object.select_all(action='DESELECT')
    for o in objs_: o.select_set(True)
    bpy.ops.export_scene.fbx(filepath=path, use_selection=True, apply_unit_scale=False, global_scale=1.0, axis_forward='-Y', axis_up='Z',
                             object_types={{'MESH'}}, mesh_smooth_type='FACE')
os.makedirs(OUT, exist_ok=True)
export(render, os.path.join(OUT, NAME + '.fbx')); export(cols, os.path.join(OUT, NAME + '_col.fbx'))
json.dump({{'lo': lo, 'hi': hi, 'objects': [o.name for o in render], 'collision': [o.name for o in cols],
           'materials': sorted({{m.name for o in render for m in o.data.materials if m}})}}, open(os.path.join(OUT, NAME + '.json'), 'w'), indent=1)
print('BLENDERKIT OK', NAME)
'''


def find_blender():
    if os.environ.get('BLENDER') and os.path.isfile(os.environ['BLENDER']): return os.environ['BLENDER']
    cands = [r'C:\Program Files (x86)\Steam\steamapps\common\Blender\blender.exe']
    cands += sorted(glob.glob(r'C:\Program Files\Blender Foundation\Blender*\blender.exe'), reverse=True)
    return next((c for c in cands if os.path.isfile(c)), None)


def script(name, out, template=None, size=None, user_script=None, imported=None, material='materials/dev/reflectivity_50.vmat', height=None):
    text = HEADER.format(out=out, name=name, material=material)
    if template:
        if template not in TEMPLATES: raise ValueError('template must be one of %s' % ', '.join(TEMPLATES))
        W, D, H = size or TEMPLATES[template][0]
        text += 'W, D, H = %r, %r, %r\n' % (float(W), float(D), float(H)) + TEMPLATES[template][1] + '\n'
    elif user_script:
        with open(user_script, encoding='utf-8') as f: text += '\n# ---- user script ----\n' + f.read() + '\n'
    elif imported:
        ext = os.path.splitext(imported)[1].lower()
        call = {'.obj': 'bpy.ops.wm.obj_import(filepath=%r)', '.fbx': 'bpy.ops.import_scene.fbx(filepath=%r)',
                '.glb': 'bpy.ops.import_scene.gltf(filepath=%r)', '.gltf': 'bpy.ops.import_scene.gltf(filepath=%r)',
                '.blend': 'bpy.ops.wm.open_mainfile(filepath=%r)'}.get(ext)
        if not call: raise ValueError('import .obj, .fbx, .glb, .gltf or .blend')
        text += call % os.path.abspath(imported) + '\n'
    else:
        raise ValueError('give a template, a script or a file to import')
    text += 'IMPORTED = %r\nTARGET = %r\n' % (bool(imported), height) + FOOTER.replace('{{', '{').replace('}}', '}')
    return text


def vmdl(rel_dir, name, materials=(), surface='default', mass=None):
    """ModelDoc vmdl (KV3 text) using <name>.fbx for render and <name>_col.fbx as hull physics"""
    remaps = ''.join('\t\t\t\t\t{\n\t\t\t\t\t\tfrom = "%s"\n\t\t\t\t\t\tto = "%s"\n\t\t\t\t\t},\n' % (m, m if m.endswith('.vmat') else 'materials/dev/reflectivity_50.vmat')
                     for m in materials)
    return ('<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} format:modeldoc29:version{3cec427c-1b0e-4d48-a90a-0436f33a6041} -->\n'
            '{\n\trootNode =\n\t{\n\t\t_class = "RootNode"\n\t\tchildren =\n\t\t[\n'
            '\t\t\t{\n\t\t\t\t_class = "MaterialGroupList"\n\t\t\t\tchildren =\n\t\t\t\t[\n\t\t\t\t\t{\n\t\t\t\t\t\t_class = "DefaultMaterialGroup"\n'
            '\t\t\t\t\t\tremaps =\n\t\t\t\t\t\t[\n' + remaps.replace('\t\t\t\t\t{', '\t\t\t\t\t\t\t{').replace('\t\t\t\t\t},', '\t\t\t\t\t\t\t},') +
            '\t\t\t\t\t\t]\n\t\t\t\t\t\tuse_global_default = false\n\t\t\t\t\t\tglobal_default_material = ""\n\t\t\t\t\t},\n\t\t\t\t]\n\t\t\t},\n'
            '\t\t\t{\n\t\t\t\t_class = "RenderMeshList"\n\t\t\t\tchildren =\n\t\t\t\t[\n\t\t\t\t\t{\n\t\t\t\t\t\t_class = "RenderMeshFile"\n'
            '\t\t\t\t\t\tfilename = "%s/%s.fbx"\n\t\t\t\t\t\timport_scale = 1.0\n\t\t\t\t\t},\n\t\t\t\t]\n\t\t\t},\n' % (rel_dir, name) +
            '\t\t\t{\n\t\t\t\t_class = "PhysicsShapeList"\n\t\t\t\tchildren =\n\t\t\t\t[\n\t\t\t\t\t{\n\t\t\t\t\t\t_class = "PhysicsHullFile"\n'
            '\t\t\t\t\t\tfilename = "%s/%s_col.fbx"\n\t\t\t\t\t\timport_scale = 1.0\n\t\t\t\t\t\tsurface_prop = "%s"\n\t\t\t\t\t\tfaceMergeAngle = 10.0\n'
            '\t\t\t\t\t\tmaxHullVertices = 64\n\t\t\t\t\t},\n\t\t\t\t]\n\t\t\t},\n' % (rel_dir, name, surface) +
            ('\t\t\t{\n\t\t\t\t_class = "PhysicsBodyMarkup"\n\t\t\t\tmass_override = %g\n\t\t\t},\n' % mass if mass else '') +
            '\t\t]\n\t\tmodel_archetype = ""\n\t\tprimary_associated_entity = ""\n\t\tanim_graph_name = ""\n\t}\n}\n')


def build(content, name, template=None, size=None, user_script=None, imported=None, material='materials/dev/reflectivity_50.vmat',
          prefix='props', surface='default', blender=None, dry_run=False, height=None, timeout=600, no_blender=False):
    """dry_run: nothing is created or written (not even the folder); the result lists would_write and carries the script text.
    no_blender: the script and the vmdl are written, Blender is not started (what dry_run meant before 11 Nov 2026)."""
    rel_dir = 'models/%s/%s' % (prefix, name)
    out = os.path.join(content, *rel_dir.split('/'))
    spath = os.path.join(out, name + '_build.py')
    text = script(name, out, template, size, user_script, imported, material, height)
    res = {'script': spath, 'vmdl': os.path.join(out, name + '.vmdl'), 'model': rel_dir + '/' + name + '.vmdl'}
    mats = [material]
    if dry_run:
        res.update(dry_run=True, script_text=text, vmdl_text=vmdl(rel_dir, name, mats, surface),
                   would_write=[spath, res['vmdl']] + ([] if no_blender else [os.path.join(out, name + '.fbx'), os.path.join(out, name + '.json')]),
                   would_overwrite=[p for p in (spath, res['vmdl']) if os.path.exists(p)])
        return res
    os.makedirs(out, exist_ok=True)
    with open(spath, 'w', encoding='utf-8') as f: f.write(text)
    if not no_blender:
        exe = blender or find_blender()
        if not exe: raise FileNotFoundError('Blender not found: pass --blender or set BLENDER')
        r = subprocess.run([exe, '--background', '--factory-startup', '--python', spath], capture_output=True, text=True, timeout=timeout,
                           creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
        res['blender_ok'] = 'BLENDERKIT OK' in r.stdout
        res['log_tail'] = (r.stdout + r.stderr).splitlines()[-15:]
        try:
            with open(os.path.join(out, name + '.json'), encoding='utf-8') as f: info = json.load(f)
            res['bounds'] = [info['lo'], info['hi']]; mats = info.get('materials') or mats
        except (OSError, ValueError):
            pass
    with open(res['vmdl'], 'w', encoding='utf-8') as f: f.write(vmdl(rel_dir, name, mats, surface))
    res['dry_run'] = False; res['blender_run'] = not no_blender
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description='Props through headless Blender')
    ap.add_argument('content'); ap.add_argument('name'); ap.add_argument('--template'); ap.add_argument('--size')
    ap.add_argument('--script'); ap.add_argument('--import', dest='imported'); ap.add_argument('--height', type=float)
    ap.add_argument('--material', default='materials/dev/reflectivity_50.vmat'); ap.add_argument('--prefix', default='props')
    ap.add_argument('--surface', default='default'); ap.add_argument('--blender'); ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--no-blender', action='store_true')
    a = ap.parse_args(argv)
    size = tuple(float(v) for v in a.size.split(',')) if a.size else None
    try:
        print(json.dumps(build(a.content, a.name, a.template, size, a.script, a.imported, a.material, a.prefix, a.surface, a.blender,
                               a.dry_run, a.height, no_blender=a.no_blender), indent=1))
    except (OSError, ValueError, subprocess.SubprocessError) as ex:
        print('blenderkit: %s' % ex, file=sys.stderr); return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
